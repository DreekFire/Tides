"""Build the paste-ready modular counterbattery script.

From the Depths does not provide a normal Lua module loader, so the source
libraries are pasted into one Lua chunk and pipeline modules are invoked from
function-scoped loaders. The legacy script is retained as the first section
to preserve behavior; Pipeline/Entry.lua then replaces only the target-data
dispatcher with the typed pipeline.
"""

from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
COUNTERBATTERY = ROOT / "Full" / "Counterbattery"
OUTPUT = COUNTERBATTERY / "CounterBatteryPipeline.lua"

WRAPPED_EXPORTS = {
    "Full/Counterbattery/Pipeline/ModuleSystem.lua": "CounterbatteryModuleSystem",
    "Full/Counterbattery/Pipeline/Types.lua": "CounterbatteryTypes",
    "Full/Counterbattery/Pipeline/TargetTracking.lua": "TargetTracking",
    "Full/Counterbattery/Pipeline/TargetAimpoint.lua": "TargetAimpoint",
    "Full/Counterbattery/Pipeline/TargetRotation.lua": "TargetRotation",
    "Full/Counterbattery/Pipeline/TargetSubobjectAimpoint.lua": "TargetSubobjectAimpoint",
    "Full/Counterbattery/Pipeline/TargetOrientation.lua": "TargetOrientation",
    "Full/Counterbattery/Pipeline/TargetDensity.lua": "TargetDensity",
    "Full/Counterbattery/Pipeline/ProjectileEstimation.lua": "TargetProjectileEstimation",
    "Full/Counterbattery/Pipeline/WeaponRateOfFire.lua": "TargetWeaponRateOfFire",
    "Full/Counterbattery/Pipeline/TrackDeduplication.lua": "TargetTrackDeduplication",
    "Full/Counterbattery/Pipeline/ProjectileHealth.lua": "CounterbatteryProjectileHealth",
    "Full/Counterbattery/Pipeline/DebugVisualization.lua": "CounterbatteryDebugVisualization",
    "Full/Counterbattery/Pipeline/TargetPipeline.lua": "CounterbatteryPipeline",
    "Full/Counterbattery/Pipeline/ClosestPointSolver.lua": "CounterbatteryClosestPointSolver",
}

parts = [
    COUNTERBATTERY / "CounterBattery.lua",
    ROOT / "Low" / "NdArray.lua",
    ROOT / "Low" / "Stats.lua",
    COUNTERBATTERY / "Pipeline" / "ModuleSystem.lua",
    COUNTERBATTERY / "Pipeline" / "Types.lua",
    COUNTERBATTERY / "Pipeline" / "TargetTracking.lua",
    COUNTERBATTERY / "Pipeline" / "TargetAimpoint.lua",
    COUNTERBATTERY / "Pipeline" / "TargetRotation.lua",
    COUNTERBATTERY / "Pipeline" / "TargetSubobjectAimpoint.lua",
    COUNTERBATTERY / "Pipeline" / "TargetOrientation.lua",
    COUNTERBATTERY / "Pipeline" / "TargetDensity.lua",
    COUNTERBATTERY / "Pipeline" / "ProjectileEstimation.lua",
    COUNTERBATTERY / "Pipeline" / "WeaponRateOfFire.lua",
    COUNTERBATTERY / "Pipeline" / "TrackDeduplication.lua",
    COUNTERBATTERY / "Pipeline" / "ProjectileHealth.lua",
    COUNTERBATTERY / "Pipeline" / "DebugVisualization.lua",
    COUNTERBATTERY / "Pipeline" / "TargetPipeline.lua",
    COUNTERBATTERY / "Pipeline" / "ClosestPointSolver.lua",
    COUNTERBATTERY / "Pipeline" / "Entry.lua",
]

with OUTPUT.open("w", encoding="utf-8", newline="\n") as output:
    output.write("-- GENERATED by Util/concat_counterbattery.py; edit Pipeline/*.lua.\n")
    for part in parts:
        marker = part.relative_to(ROOT).as_posix()
        output.write(f"\n-- BEGIN {marker}\n")
        source = part.read_text(encoding="utf-8")
        source = "\n".join(line.rstrip() for line in source.splitlines())
        export = WRAPPED_EXPORTS.get(marker)
        if export:
            loader = f"_load_{export}"
            output.write(f"function {loader}()\n")
            output.write(source)
            output.write(f"\n_G.{export} = {export}\nend\n")
            output.write(f"{loader}()\n_G.{loader} = nil\n")
        else:
            output.write(source)
        output.write(f"\n-- END {marker}\n")

generated = OUTPUT.read_text(encoding="utf-8")
for part in parts[1:]:
    marker = part.relative_to(ROOT).as_posix()
    if f"-- BEGIN {marker}" not in generated or f"-- END {marker}" not in generated:
        raise RuntimeError(f"missing generated markers for {marker}")
    export = WRAPPED_EXPORTS.get(marker)
    if export and f"function _load_{export}()" not in generated:
        raise RuntimeError(f"missing module wrapper for {marker}")
if generated.count("function UpdateEnemyData(I)") != 2:
    raise RuntimeError("expected the legacy dispatcher and one pipeline dispatcher")

print(OUTPUT)
